package extract

import (
	"html"
	"regexp"
	"strings"
	"unicode"
)

// Отбор «питча» для meta-description из описания объекта.
//
// Описания приходят с сайта-агрегатора одним сплошным абзацем (медиана 1687
// символов у 313 объектов из 319), поэтому разбор идёт по предложениям, а не по
// строкам: разбиение по \n на таких данных не срабатывает вовсе.
//
// Два правила, ради которых всё написано. Первое: в сниппет не должен попадать
// голос владельца объекта — «Мы рады предложить вам», «Наш глэмпинг». В выдаче
// такой текст подписан нашим доменом, а с владельцами 313 объектов у нас нет
// никаких отношений. Второе: описание обязано укладываться в лимит целиком,
// вместе с именем и призывом, иначе поисковик обрывает его многоточием.

const (
	// Предельная длина ВСЕГО description. Поисковик показывает ~150-160
	// символов; лимит на один лишь питч (как было) не спасает — имя и призыв
	// прибавляются сверху.
	seoDescTotalRunes = 150
	// Ниже этого питч не берём: обрывок вида «Тихий уголок» ничего не говорит.
	seoMinPitchRunes = 40
)

// Голос владельца: местоимения первого лица.
//
// Границы слова заданы через (^|[^\p{L}]), а НЕ через \b: в RE2 \b определён
// только для ASCII, кириллица словной не считается, и правило на \b молча
// не срабатывает нигде (проверено прогоном: `\bмы\b` не находит «мы» ни в
// «Костромы», ни в «мы рады»).
var firstPersonRe = regexp.MustCompile(
	`(?i)(^|[^\p{L}])(мы|нас|нам|нами|наш|наша|наше|наши|нашего|нашей|нашем|нашему|наших|нашим|нашими|нашу|я|мне|меня|мной|мною|мой|моя|мои|моего|моей|моих|моим|мою)([^\p{L}]|$)`)

// Глаголы первого лица без местоимения: русский позволяет его опустить, и
// «Приглашаем вас отдохнуть» выдаёт говорящего ровно так же, как «мы».
var firstPersonVerbRe = regexp.MustCompile(
	`(?i)(^|[^\p{L}])(приглаша(ем|ю)|предлага(ем|ю)|жд(ём|ем|у)|построил[аи]?|создал[аи]?|рады|рад|рада|позаботили(сь)?|подготовил[аи]?|встретим|поможем|организуем|сделал[аи]?|постарали(сь)?|располагаем|дарим|предоставляем|обеспечим|учли|гарантируем|принимаем|сда(ём|ем)|работаем|добавим)([^\p{L}]|$)`)

// Императивы-зазывалки: «Приезжайте», «Живите в гармонии с природой!». Это
// реклама владельца, а не описание места. Заодно ловит шаблонные шапки
// агрегатора, дававшие одинаковые сниппеты нескольким объектам сразу.
var invitationRe = regexp.MustCompile(
	`(?i)(^|[^\p{L}])(приезжайте|приходите|бронируйте|звоните|пишите|приезжай|бронируй|успейте|закажите|забронируйте|живите|поживите|представьте|мечтаете|забудьте|добро пожаловать)([^\p{L}]|$)`)

// Регламент проживания: время заезда, залог, запреты. Факт, но не презентация.
var houseRulesRe = regexp.MustCompile(
	`(?i)(запрещ|нельзя|залог|предоплат|депозит|заезд с|выезд до|заселени|курени|до \d+ лет|правила)`)

// Единицы измерения — признак технической строки («85 кв.м, до 6 гостей»).
var unitsRe = regexp.MustCompile(`(?i)\d\s*(кв\.?\s*м|м²|м2|га|чел|мест|гостей|спальн|квадратн)`)

// Рубрика в начале: «Расположение и окружение:», «Общая информация».
var headingRe = regexp.MustCompile(
	`(?i)^(общая информация|расположение|окружение|удобства|преимущества|условия|правила|питание|площадь|локация|инфраструктура|описание|размещение|проживание|время|о нас|контакты)(\s+и\s+\p{L}+)?\s*[:—-]*\s*`)

// Тематическое слово места — позитивный фильтр: без него в питч попадают
// служебные фразы, формально прошедшие все запреты.
var placeWordRe = regexp.MustCompile(
	`(?i)(лес|озер|рек|природ|дом|бан|берег|вид|тишин|сосн|бор|пляж|гор|парк|сад|поле|луг|усадьб|глэмпинг|коттедж|шале|фрейм|купел|чан|терасс|террас|камин|уедин|воздух|водохранилищ|пруд|ферм|деревн|село)`)

// Служебное слово в хвосте — верный признак того, что склейку разрезали не
// там: «…рядом с озером, где Вы», «…парковка рядом с домом Здесь». Проверяется
// у любого кандидата.
var serviceTailRe = regexp.MustCompile(
	`(?i)(^|[^\p{L}])(в|во|на|у|к|с|со|из|от|до|за|по|при|для|без|и|а|но|или|это|где|когда|который|которая|которое|что|чтобы|если|вы|вам|вас|мы|нас|здесь|тут|там|также|каждый|каждая|каждое|все|всё|есть|этот|эта|эти)$`)

// Прилагательное в хвосте («…рядом с живописным») — обрыв мысли, но проверять
// его можно ТОЛЬКО у половинок разрезанной склейки. У целого предложения те же
// окончания сплошь и рядом принадлежат существительным в творительном падеже:
// «озером», «лесом», «Залесским» кончаются на -ом/-им и обрывом не являются.
var danglingAdjRe = regexp.MustCompile(
	`(?i)(^|[^\p{L}])\p{L}*(ого|его|ый|ий|ая|яя|ое|ее|ые|ие|ую|юю|ых|их)$`)

// Двоеточие внутри кандидата — рубрика или перечисление («Санузел: оборудован
// тёплым полом», «На территории дома: купель мангальная зона парковка»).
// Голова до двоеточия предлагается отдельным кандидатом, а хвост-перечисление
// в сниппет не годится никогда.
var colonRe = regexp.MustCompile(`:`)

// Склейка заголовка карточки с телом текста без точки: источник отдаёт
// «Уютное пространство на Волге Мы рады предложить вам…». Разбор по точке
// такое не делит, и чужой голос едет прицепом к хорошему заголовку. Ищем
// заглавное слово, которым топоним начинаться не может.
var glueRe = regexp.MustCompile(
	`\p{Ll},? (В|Во|На|Над|Под|У|К|Ко|С|Со|Из|От|До|За|По|При|Для|Про|Без|Через|Около|И|А|Но|Или|Это|Этот|Эта|Эти|Здесь|Тут|Там|Все|Всё|Каждый|Каждая|Каждое|Есть|Также|Кроме|Помимо|Вы|Вам|Вас|Ваш|Ваша|Ваше|Ваши|Мы|Наш|Наша|Наше|Наши|Я|Что|Чтобы|Если|Когда|Где|Приглашаем|Предлагаем|Представьте|Добро)([^\p{L}]|$)`)

var nbspReplacer = strings.NewReplacer(" ", " ", " ", " ", " ", " ")

// Схлопываем пробелы, но НЕ переводы строк: у описаний из ВК перенос — это
// единственная граница предложения (точек в них нет вовсе), и схлопывание
// склеивало весь текст в одну строку с «Забронировать» внутри.
var spacesRe = regexp.MustCompile(`[^\S\n]+`)
var newlinesRe = regexp.MustCompile(`\n+`)
var spaceBeforePunctRe = regexp.MustCompile(`[^\S\n]+([,.!?;:])`)

// normalizeAbout приводит описание к виду, пригодному для разбора.
func normalizeAbout(about string) string {
	s := html.UnescapeString(about)
	s = emojiRe.ReplaceAllString(s, " ")
	s = nbspReplacer.Replace(s)
	s = spacesRe.ReplaceAllString(s, " ")
	s = newlinesRe.ReplaceAllString(s, "\n")
	s = spaceBeforePunctRe.ReplaceAllString(s, "$1")
	return strings.TrimSpace(s)
}

// sentences режет текст на предложения ручным сканером по рунам.
//
// Регуляркой это не выражается: RE2 не умеет lookbehind, а границу задаёт
// именно контекст вокруг точки. Три случая, каждый встречается в данных:
// точка без пробела перед заглавной («реки Нерль.Идеальное место») — граница;
// сокращение (одна-две кириллические буквы перед точкой: «г.», «д.») —
// не граница; латиница перед точкой («Wi-Fi.») — граница, иначе следующее
// предложение слипается с предыдущим.
func sentences(text string) []string {
	runes := []rune(text)
	out := make([]string, 0, 8)
	start := 0

	flush := func(end int) {
		part := strings.TrimSpace(string(runes[start:end]))
		if part != "" {
			out = append(out, part)
		}
	}

	for i, r := range runes {
		// Начало уже перепрыгнуло вперёд (сканер съел пробелы после
		// терминатора) — эти руны разобраны, их пропускаем.
		if i < start {
			continue
		}
		if r == '\n' {
			flush(i)
			start = i + 1
			continue
		}
		if r != '.' && r != '!' && r != '?' && r != '…' {
			continue
		}
		if r == '.' && isAbbreviation(runes, i) {
			continue
		}
		// Границей считаем терминатор, за которым идёт заглавная, цифра или
		// кавычка — с пробелом или без.
		j := i + 1
		for j < len(runes) && (runes[j] == ' ' || runes[j] == '.' || runes[j] == '!' || runes[j] == '?') {
			j++
		}
		if j >= len(runes) {
			flush(i + 1)
			start = len(runes)
			break
		}
		next := runes[j]
		if unicode.IsUpper(next) || unicode.IsDigit(next) || next == '«' || next == '"' {
			flush(i + 1)
			start = j
		}
	}
	if start < len(runes) {
		flush(len(runes))
	}
	return out
}

// isAbbreviation — точка после одной-двух кириллических букв («г.», «кв.»),
// то есть сокращение, а не конец предложения. Для латиницы не применяем:
// «Wi-Fi.» — обычный конец фразы.
func isAbbreviation(runes []rune, dot int) bool {
	n := 0
	for i := dot - 1; i >= 0 && n < 3; i-- {
		r := runes[i]
		if !unicode.IsLetter(r) {
			break
		}
		if !unicode.Is(unicode.Cyrillic, r) {
			return false
		}
		n++
	}
	return n > 0 && n <= 2
}

// candidates даёт варианты питча из одного предложения, от лучшего к худшему.
func candidates(sentence, name string) []string {
	base := headingRe.ReplaceAllString(sentence, "")
	base = strings.TrimSpace(base)
	if base == "" {
		return nil
	}

	out := make([]string, 0, 3)
	add := func(s string) {
		s = strings.TrimSpace(strings.Trim(strings.TrimSpace(s), " .!?…,;:—-"))
		if s != "" {
			out = append(out, s)
		}
	}

	// Склейка заголовка с телом: обе половины — самостоятельные кандидаты,
	// целое отбрасываем (в нём заведомо сидит чужой голос). Половинку,
	// оборванную на прилагательном, не берём — разрез пришёлся не туда.
	if loc := glueRe.FindStringIndex(base); loc != nil {
		cut := strings.LastIndex(base[:loc[1]], " ")
		if cut > 0 {
			for _, half := range []string{base[:cut], base[cut:]} {
				if !danglingAdjRe.MatchString(strings.Trim(strings.TrimSpace(half), " .!?…,;:—-")) {
					add(half)
				}
			}
			return dropName(out, name)
		}
	}

	// Голова до двоеточия — законченная мысль, а перечисление за ним в питч
	// не годится никогда.
	if i := strings.Index(base, ":"); i > 0 {
		add(base[:i])
	}
	add(base)
	return dropName(out, name)
}

// dropName снимает ведущее имя объекта: «Сабадури — А-фрейм в лесу» после
// «Сабадури — » читалось бы как «Сабадури — сабадури — А-фрейм в лесу».
func dropName(items []string, name string) []string {
	n := strings.ToLower(strings.TrimSpace(name))
	if n == "" {
		return items
	}
	out := make([]string, 0, len(items))
	for _, s := range items {
		if strings.HasPrefix(strings.ToLower(s), n) {
			rest := strings.TrimLeft(s[len(n):], " —-:,.")
			if len([]rune(rest)) >= seoMinPitchRunes {
				out = append(out, rest)
				continue
			}
		}
		out = append(out, s)
	}
	return out
}

// suitable — годится ли кандидат в сниппет агрегатора.
func suitable(s string) bool {
	r := []rune(s)
	if len(r) < seoMinPitchRunes || !unicode.IsUpper(r[0]) {
		return false
	}
	if !placeWordRe.MatchString(s) {
		return false
	}
	if serviceTailRe.MatchString(s) {
		return false
	}
	for _, re := range []*regexp.Regexp{
		firstPersonRe, firstPersonVerbRe, invitationRe,
		houseRulesRe, unitsRe, junkLineRe, headingRe, colonRe,
	} {
		if re.MatchString(s) {
			return false
		}
	}
	return true
}

// pickPitch выбирает первый годный фрагмент, целиком влезающий в бюджет.
//
// Ровно один фрагмент и никакой обрезки по словам: обрыв поисковик дорисует
// сам, а собственное многоточие читается как поломка генератора. Добор второго
// фрагмента замерялся отдельно и не менял результат ни на один объект.
func pickPitch(about, name string, budget int) string {
	if budget < seoMinPitchRunes {
		return ""
	}
	for _, sentence := range sentences(normalizeAbout(about)) {
		for _, c := range candidates(sentence, name) {
			if len([]rune(c)) <= budget && suitable(c) {
				return c
			}
		}
	}
	return ""
}
