// Package rx — границы слова, работающие с кириллицей.
//
// В Go RE2 (как и в JavaScript) `\b` определяется через класс `\w`, а он —
// только `[0-9A-Za-z_]`. Кириллица туда не входит, поэтому `\bкм\b` МОЛЧА не
// совпадает ни с чем: ошибки нет, паники нет, просто ничего не находится.
//
// Эта грабля ловила проект четыре раза за один день:
//   - нормализация «Ивановская обл.» → «область» не срабатывала вовсе;
//   - маркер расстояния `\bкм\b` не видел «2 км», и чужая баня в двух
//     километрах засчитывалась как удобство объекта;
//   - `курен` не ловил «курить», и правило про курение подменялось дефолтом;
//   - `барн\b` не находил «Дом „Барн“» — объект оставался без типа жилья.
//
// Отсюда этот пакет: границу слова для кириллицы надо писать явно, и лучше
// одним способом на весь проект, чем каждый раз заново.
package rx

import (
	"regexp"
	"strings"
)

// Границы слова. Класс `\pL` в RE2 покрывает буквы любого алфавита, включая
// кириллицу, — в отличие от `\w`, на который опирается `\b`.
//
// Цифры границей СЧИТАЮТСЯ: «70км.» и «2 км» — обычная запись расстояния, а
// буквой слово ограничивать нельзя («мкм» не должно совпадать с «км»).
const (
	boundaryBefore = `(?:^|[^\pL])`
	boundaryAfter  = `(?:[^\pL]|$)`
)

// Word строит выражение «слово целиком» — замена `\bслово\b`, работающая с
// кириллицей.
//
//	rx.Word("км")        совпадёт с «2 км», «км.», «км»
//	                     и НЕ совпадёт с «километр», «мкм»
//
// Регистр не учитывается: источники пишут вперемешку.
func Word(word string) *regexp.Regexp {
	return regexp.MustCompile(`(?i)` + boundaryBefore + regexp.QuoteMeta(word) + boundaryAfter)
}

// WordStart строит выражение «слово начинается с этой основы» — для падежей:
// «барн» найдёт «БарнХаус» и «Барн», но не «кабарнет».
//
//	rx.WordStart("бан")  совпадёт с «баня», «бане», «банный»
//	                     и НЕ совпадёт с «кабан», «ванна»
func WordStart(stem string) *regexp.Regexp {
	return regexp.MustCompile(`(?i)` + boundaryBefore + regexp.QuoteMeta(stem))
}

// AnyWordStart — то же для набора основ: одно выражение вместо склейки руками.
// Пустой список даёт выражение, которое не совпадает ни с чем.
func AnyWordStart(stems ...string) *regexp.Regexp {
	if len(stems) == 0 {
		// `$^` выглядит как «ничего не совпадёт», но с ПУСТОЙ строкой совпадает:
		// конец и начало там в одной точке. Правило без основ должно молчать
		// всегда, иначе объект без названия получит форму жилья из ниоткуда.
		return regexp.MustCompile(`\z.`)
	}
	quoted := make([]string, 0, len(stems))
	for _, s := range stems {
		quoted = append(quoted, regexp.QuoteMeta(s))
	}
	return regexp.MustCompile(`(?i)` + boundaryBefore + `(?:` + strings.Join(quoted, "|") + `)`)
}

// AnyWord — любое из слов (или словосочетаний) целиком, с границами по обе
// стороны. Нужен там, где основы мало: «на дереве» как начало совпадает и с
// «на деревенской улице», а это другое место.
func AnyWord(words ...string) *regexp.Regexp {
	if len(words) == 0 {
		return regexp.MustCompile(`\z.`)
	}
	quoted := make([]string, 0, len(words))
	for _, w := range words {
		quoted = append(quoted, regexp.QuoteMeta(w))
	}
	return regexp.MustCompile(
		`(?i)` + boundaryBefore + `(?:` + strings.Join(quoted, "|") + `)` + boundaryAfter,
	)
}
