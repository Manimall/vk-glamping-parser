package avito

import "testing"

// Адрес показа: регион и населённый пункт, без улицы и номера дома. Авито
// отдаёт точный адрес, но публиковать его нельзя — владелец согласия не давал,
// а строка уезжает и в плитку каталога, и в <title> пререндеренной страницы.
func TestPublicAddress(t *testing.T) {
	cases := []struct{ name, address, want string }{
		{
			"улица и дом отброшены",
			"Ивановская область, Ивановский р-н, Коляновское сельское поселение, д. Коляново, Садовая ул., 32",
			"Ивановская область, д. Коляново",
		},
		{"улица типом впереди", "Ивановская область, Иваново, пр-т Ленина", "Ивановская область, Иваново"},
		{"улица словом", "Московская область, Клин, Советская улица, 12", "Московская область, Клин"},
		{"набережная", "Тверская область, Конаково, наб. Волжская, 5", "Тверская область, Конаково"},
		{"город федерального значения", "Москва, ул. Тверская, 1", "Москва"},

		// Сокращение типа улицы не должно съедать имя населённого пункта: у
		// «Шарьи» и «Прохоровки» в начале те же буквы, что у «ш.» и «пр.».
		{"посёлок с похожим началом", "Костромская область, Шарья", "Костромская область, Шарья"},
		{"район отброшен как лишний", "Ивановская область, Ивановский муниципальный округ, с. Тюрюково", "Ивановская область, с. Тюрюково"},

		{"один сегмент", "Ивановская область", "Ивановская область"},
		{"пусто", "", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := publicAddress(c.address); got != c.want {
				t.Errorf("publicAddress(%q) = %q, ожидалось %q", c.address, got, c.want)
			}
		})
	}
}

// canonAddress трогает ТОЛЬКО форму записи региона. Всё остальное обязано
// доехать байт в байт: функция стоит в начале цепочки, и порча здесь
// разошлась бы по всем полям карточки разом.
func TestCanonAddressKeepsRest(t *testing.T) {
	cases := []struct{ name, address, want string }{
		{"разворачивает первый сегмент", "Ивановская обл., Иваново", "Ивановская область, Иваново"},
		{"полную форму не трогает", "Московская область, Клин", "Московская область, Клин"},
		{"не регион — не трогает", "Москва, ул. Тверская, 1", "Москва, ул. Тверская, 1"},
		{"без запятой", "Ивановская обл.", "Ивановская область"},
		{"пусто", "", ""},
		{"хвост сохраняется целиком", "Тверская обл., Конаково, д. 5, кв. 2", "Тверская область, Конаково, д. 5, кв. 2"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := canonAddress(c.address); got != c.want {
				t.Errorf("canonAddress(%q) = %q, ожидалось %q", c.address, got, c.want)
			}
		})
	}
}

