package avito

import (
	"strings"
	"testing"
)

func TestRegion(t *testing.T) {
	cases := []struct{ name, address, want string }{
		// Сокращение источника обязано развернуться: каталог группирует по
		// совпадению строки, и «обл.» рядом с «область» даёт регион-двойник,
		// в котором объекты Авито прячутся от фильтра.
		{"сокращение разворачивается", "Ивановская обл., Иваново, пр-т Ленина", "Ивановская область"},
		{"сокращение без точки", "Тверская обл, Конаково", "Тверская область"},
		{"автономный округ", "Ханты-Мансийский АО, Сургут", "Ханты-Мансийский автономный округ"},

		// Республику Авито пишет и перед названием, и после него: перед —
		// когда имя существительное («Респ. Карелия»), после — когда
		// прилагательное («Чувашская Респ.»). Вторую форму разбор терял вовсе,
		// а сайт при пустом регионе подставляет в ось группировки ВЕСЬ адрес,
		// вместе с улицей и номером дома.
		{"республика с точкой", "Респ. Карелия, Сортавала", "Республика Карелия"},
		{"республика без точки", "Респ Татарстан, Казань", "Республика Татарстан"},
		{"республика суффиксом", "Чувашская Респ., Чебоксары", "Чувашская Республика"},
		{"республика суффиксом без точки", "Удмуртская Респ, Ижевск", "Удмуртская Республика"},

		// Единственная в стране автономная ОБЛАСТЬ сокращается и как «Аобл», и
		// как «АО», а «АО» в остальных случаях — округ. Общее правило давало
		// «Еврейская автономный округ»: безграмотно и вдобавок двойник.
		{"ЕАО сокращением области", "Еврейская Аобл, Биробиджан", "Еврейская автономная область"},
		{"ЕАО сокращением округа", "Еврейская АО, Биробиджан", "Еврейская автономная область"},

		// Адрес одним сегментом: у сервисных объявлений встречается, а форму
		// записи видно и без запятой.
		{"регион без продолжения", "Ивановская обл.", "Ивановская область"},

		// Полные формы — те самые, которые выдаёт словарь выше. Не узнавать их
		// значит терять регион у объекта, чей адрес источник записал целиком:
		// на «Республике Карелия» и «Ямало-Ненецком автономном округе» разбор
		// возвращал пустоту, и объект выпадал из фильтра каталога.
		{"полное слово не трогаем", "Московская область, Клин", "Московская область"},
		{"край пишется полностью", "Краснодарский край, Сочи", "Краснодарский край"},
		{"республика полностью", "Республика Карелия, Сортавала", "Республика Карелия"},
		{"республика второй частью", "Чувашская Республика, Чебоксары", "Чувашская Республика"},
		{"округ полностью", "Ямало-Ненецкий автономный округ, Салехард", "Ямало-Ненецкий автономный округ"},
		{"автономная область", "Еврейская автономная область, Биробиджан", "Еврейская автономная область"},

		// Город федерального значения: первый сегмент — сразу город. Подставить
		// его в Region нельзя, это ось группировки каталога.
		{"город вместо региона", "Москва, ул. Тверская, 1", ""},
		{"адрес без запятых", "Иваново", ""},
		{"пусто", "", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := region(c.address); got != c.want {
				t.Errorf("region(%q) = %q, ожидалось %q", c.address, got, c.want)
			}
		})
	}
}

// Списки сокращений и распознавание регионов легко разъезжаются: словарь
// пополняют, а проверку «это вообще регион» забывают. Тогда объект молча
// выпадает из фильтра. Тест держит их связанными.
func TestEveryExpansionIsRecognized(t *testing.T) {
	for _, e := range regionSuffixExpansions {
		address := "Тестовая" + e.short + ", Город"
		if got := region(address); got == "" {
			t.Errorf("сокращение %q не признано регионом: region(%q) пусто", e.short, address)
		}
	}
	for _, e := range regionPrefixExpansions {
		address := e.short + "Тестовая, Город"
		if got := region(address); got == "" {
			t.Errorf("сокращение %q не признано регионом: region(%q) пусто", e.short, address)
		}
	}
}

// Строка места на плитке каталога сокращается до региона по совпадению
// префикса (displayLocation на сайте: `place.startsWith(area) ? area : place`).
// Разойдись форма записи между Region и Location — и в плитку вместо названия
// региона уедет адрес целиком, вплоть до номера дома частного владельца.
func TestLocationStartsWithRegion(t *testing.T) {
	addresses := []string{
		"Ивановская обл., Ивановский р-н, д. Коляново, Садовая ул., 32",
		"Чувашская Респ., Чебоксары, ул. Ленина, 5",
		"Респ. Карелия, Сортавала",
		"Еврейская АО, Биробиджан",
		"Московская область, Клин",
	}
	for _, address := range addresses {
		t.Run(address, func(t *testing.T) {
			obj := toObject(&buyerItem{Item: avitoItem{ID: 1, Title: "Дом", Price: 1000, Address: address}})
			if obj.Region == "" {
				t.Fatalf("регион не распознан у %q", address)
			}
			if !strings.HasPrefix(obj.Location, obj.Region) {
				t.Errorf("плитка покажет адрес целиком:\n  регион:  %q\n  адрес:   %q", obj.Region, obj.Location)
			}
		})
	}
}

// Разворот обязан быть устойчивым: полная форма, поданная снова, не должна
// меняться. Иначе «автономный округ» после второго прогона стал бы другим
// значением, а в каталоге — вторым регионом.
func TestExpansionIsIdempotent(t *testing.T) {
	for _, e := range regionSuffixExpansions {
		full := "Тестовая" + e.full
		if got := region(full + ", Город"); got != full {
			t.Errorf("повторный разбор %q дал %q", full, got)
		}
	}
}
