package glamping_rf

import "strings"

// Источник отдаёт amenityFeature плоским списком, смешивая РУБРИКИ каталога с
// их значениями: рядом с «Мангальная зона» лежат «Территория», «Развлечения»,
// «Дети». В карточке объекта это читается как список удобств, и гость видит
// «Дети» и «Общие» среди бани и рыбалки.
//
// Проверено на выгрузке парсера (309 объектов, generated/glamping_rf): рубрики
// есть почти у всех — «Территория» у 308, «Развлечения» у 259, «Дети» у 192, —
// а настоящие удобства так не распределены. Второй, более сильный признак:
// рубрика ВСЕГДА в хвосте списка (доля вхождений после первой известной рубрики
// 1.00), а любое настоящее удобство — всегда до них (0.00).
//
// Стоп-лист привязан к плоскому amenityFeature глэмпинги.рф. Поднимать его в
// общий пакет нельзя без пересчёта: internal/extract/dictionary.go канонизирует
// связь ИМЕННО в лейбл «Интернет», и у объектов других провайдеров он бывает
// единственным упоминанием — например у aframe-iv.
var amenityRubrics = map[string]bool{
	"территория":  true,
	"развлечения": true,
	"дети":        true,
	"общие":       true,
	"общее":       true,
	"прочее":      true,
	// Рубрика: рядом всегда лежат конкретные «WI-FI» (289 из 300) и
	// «Мобильный интернет», а сама строка ничего не добавляет.
	"интернет": true,
	// Рубрика «можно ли с питомцем». Её значения приходят отдельными строками
	// и без неё читаются сами: «Можно с Питомцем» — у 268 объектов.
	"домашние животные": true,
	// Та же связка: у 47 из 48 объектов рядом лежит конкретное «Подходит для
	// проведения мероприятий», а сама строка стоит в хвосте после «Общие».
	"праздничные и корпоративные мероприятия": true,
}

// «Нельзя» — значение рубрики о питомцах, потерявшее вопрос: в списке читается
// как удобство под названием «Нельзя». Убирать безопасно — у всех 37 объектов
// с этой строкой petsAllowed=false, смысл уже разобран в поле.
//
// «Можно только с согласованием» СЮДА НЕ ВХОДИТ намеренно: у обоих объектов с
// этой строкой petsAllowed=null, и она — единственный носитель информации о
// питомцах. Убрав её, гость вместо «можно по согласованию» получит молчание.
var amenityOrphanValues = map[string]bool{
	"нельзя": true,
}

// Разные написания одного и того же. Только бесспорные случаи: «Баня» и
// «Сауна» здесь намеренно НЕ склеены — это разные вещи, как и общая кухня
// против собственной.
var amenityCanonical = map[string]string{
	"wi-fi": "Wi-Fi",
	"wifi":  "Wi-Fi",
}

// cleanAmenities убирает рубрики и осиротевшие значения, сводит написания и
// снимает дубли, сохраняя исходный порядок.
func cleanAmenities(names []string) []string {
	seen := make(map[string]bool, len(names))
	out := make([]string, 0, len(names))
	for _, raw := range names {
		name := strings.TrimSpace(raw)
		if name == "" {
			continue
		}
		key := strings.ToLower(name)
		if amenityRubrics[key] || amenityOrphanValues[key] {
			continue
		}
		if canonical, ok := amenityCanonical[key]; ok {
			name = canonical
			key = strings.ToLower(canonical)
		}
		if seen[key] {
			continue
		}
		seen[key] = true
		out = append(out, name)
	}
	if len(out) == 0 {
		return nil
	}
	return out
}
