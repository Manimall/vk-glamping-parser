package glamping_rf

// Характеристики домиков из window.pv12RoomDetails: площадь, спальные места и
// вместимость.
//
// Прежде вместимость искалась регуляркой по ВЁРСТКЕ и не находилась почти
// нигде — почти весь каталог получал дефолтное «до 4 гостей». Гость видел
// «до 4», ехал вчетвером, а его ждала одна двуспальная кровать.
//
// Разбор на живых страницах: слово «Вместимость» в разметке есть, но между ним
// и числом стоят HTML-теги («<strong>Вместимость:</strong></p><ul><li><p>
// Возможно размещение до 4-х человек»), а вместо «гостей» часто «человек».
// Регулярка по плоскому тексту такого не переживает — поэтому и берём данные
// из встроенного JSON, где они лежат структурно.
//
// Данные лежат в том же JSON, который парсер уже разбирает ради платных услуг:
//
//	specs: ["📐 32 м²", "🛌 1 двуспальная"]
//	desc:  "Вместимость: до 6 гостей (…)"
//
// Заявление источника всегда важнее нашей арифметики по кроватям: оно
// учитывает и правила объекта, и то, что кровать бывает детской.

import (
	"encoding/json"
	"log/slog"
	"regexp"
	"strconv"
	"strings"
)

// areaSpecRe — площадь домика: «📐 32 м²», «📐 32.5 м²», «📐 32,5 м²». Значок
// игнорируем, он может смениться; опираемся на число перед «м²».
//
// Дробная часть в шаблоне обязательна, хотя площадь мы округляем до целых:
// без неё регулярка совпадала с ХВОСТОМ числа — «32.5 м²» давало 5 м², то есть
// домик уменьшался в шесть раз ровно там, где источник был точнее обычного.
var areaSpecRe = regexp.MustCompile(`(\d+)(?:[.,](\d+))?\s*м²`)

// bedSpecRe — спальное место: «🛌 1 двуспальная», «🛏 2 односпальная»,
// «🛋 1 диван-кровать». Число впереди — сколько таких мест.
var bedSpecRe = regexp.MustCompile(`(?i)(\d+)\s*(двуспальн|односпальн|диван)`)

// Сколько гостей помещается на одно спальное место каждого вида.
//
// Диван-кровать — ОДИН гость, а не двое. Сверка с заявлениями источника на
// живых страницах: «3 двуспальные + диван» у него «до 6», а не 8; «1 дв. +
// 2 одн. + диван» — «до 5», а не 6. Оба расхождения дал именно диван, и оба в
// сторону завышения — то есть ровно та ошибка, от которой уходили: гость видит
// число, едет такой компанией, а места нет.
const (
	guestsPerDouble = 2
	guestsPerSingle = 1
	guestsPerSofa   = 1
)

const (
	// capacityWindow — сколько символов допускаем между словом «вместимость» и
	// числом: «Вместимость: до 6 гостей», «Вместимость — до 4-х гостей».
	capacityWindow = 20
	// capacityMax — потолок правдоподобной вместимости домика. Больше — это уже
	// не жильё, а банкетный зал, и число относится не к ночёвке.
	capacityMax = 40
	// kidsWindow — сколько символов допускаем между словом про взрослых и
	// слагаемым про детей: «6 взрослых + 2 детей», «4 взрослых и + 2 ребёнка».
	// Окно узкое намеренно: дальше по описанию идут другие числа — возраст, до
	// которого ребёнок считается ребёнком, или площадь, — и их складывать
	// с вместимостью нельзя.
	kidsWindow = 10
)

// declaredCapacityRe — вместимость, названная источником прямо в описании
// комнаты.
//
// Число ОБЯЗАНО стоять рядом со словом про людей. Без этой привязки регулярка
// брала первое попавшееся: «Вместимость домика 32 м², спальных мест 4» давала
// тридцать двух гостей, а «Вместимость дома — 3 спальни, 2 санузла, до 8
// гостей» — троих. И то и другое перезаписывало верный расчёт по кроватям.
//
// Старая регулярка по вёрстке (capacityRe) не совпадала по другой причине: там
// между двоеточием и числом стоят HTML-теги, а вместо «гостей» бывает
// «человек».
//
// Сокращение «чел» закрывается не через `\b`, а через «дальше не буква или
// конец строки»: `\b` в Go RE2 опирается на латиницу и после кириллицы молча
// не срабатывает — «до 3 чел» в конце строки так и не находилось.
//
// «Взрослых» источник считает ОТДЕЛЬНО от детей: «Вместимость: 6 взрослых + 2
// детей до 18 лет». Гостю нужна одна цифра — сколько человек поместится, — и
// это восемь. Поэтому вторая группа необязательная: есть хвост про детей —
// складываем, нет — берём одних взрослых.
//
// Ни одну из половин нельзя выкинуть. Без слова «взрослых» объект уходит на
// расчёт по кроватям: у «У сердца» источник говорит «4 взрослых», а кровати
// дают три — семья вчетвером не нашла бы подходящее жильё. Без слагаемого про
// детей — обратная ошибка: «4 взрослых + 2 детей» превращается в четверых.
var declaredCapacityRe = regexp.MustCompile(
	`(?i)вместимость[^0-9]{0,` + strconv.Itoa(capacityWindow) +
		`}(\d{1,3})\s*(?:-?х\s*)?(?:гост|человек|персон|взросл|чел(?:[^\pL]|$))` +
		`(?:[^0-9]{0,` + strconv.Itoa(kidsWindow) + `}\+\s*(\d{1,2})\s*(?:-?х\s*)?(?:дет|реб))?`,
)

// roomSpecs — характеристики домика: площадь в м² и вместимость по спальным
// местам. Нули означают «источник не сказал»: подставлять дефолт нельзя,
// именно так и появилось выдуманное «до 4».
type roomSpecs struct {
	AreaM2 int
	Guests int
}

// pv12RoomWithSpecs — домик из встроенного JSON целиком: название, описание,
// характеристики и удобства.
//
// Одна структура на весь домик, а не две по числу потребителей: раньше рядом
// жил pv12Room с одними лишь услугами, и тот же JSON разбирался дважды за один
// проход по странице в сотни килобайт.
type pv12RoomWithSpecs struct {
	Name      string        `json:"name"`
	Desc      string        `json:"desc"`
	Specs     []string      `json:"specs"`
	Amenities []pv12Amenity `json:"amenities"`
}

// parseRoomsWithSpecs — домики объекта из встроенного JSON. Единая точка
// разбора: страница весит сотни килобайт, и повторять по ней поиск JSON ради
// каждого поля незачем.
func parseRoomsWithSpecs(page string) map[string]pv12RoomWithSpecs {
	raw := balancedJSON(page, roomDetailsMarker, '{', '}')
	if raw == "" {
		return nil
	}
	var rooms map[string]pv12RoomWithSpecs
	if err := json.Unmarshal([]byte(raw), &rooms); err != nil {
		// Молчать здесь нельзя. Смена формата у источника обнулит вместимость и
		// формы жилья у всего каталога, и узнаем мы об этом так же, как в
		// прошлый раз — по тому, что данные «почему-то» пропали, спустя недели.
		// Ровно этот класс сбоя и чинит весь остальной PR.
		slog.Warn("glamping_rf: pv12RoomDetails не разобрался", "ошибка", err, "длина", len(raw))
		return nil
	}
	return rooms
}

// parseRoom — характеристики ОДНОГО домика.
//
// Вместимость: сначала то, что источник назвал прямо в описании, и только при
// его молчании — арифметика по спальным местам. Заявление всегда точнее: оно
// учитывает и правила объекта, и то, что кровать бывает детской.
func parseRoom(room pv12RoomWithSpecs) roomSpecs {
	out := parseRoomSpecs(room.Specs)
	if n := declaredCapacity(room.Desc); n > 0 {
		out.Guests = n
	}
	return out
}

// declaredCapacity — вместимость, названная источником, одним числом. Ноль
// означает «источник промолчал» — тогда решает расчёт по спальным местам.
func declaredCapacity(desc string) int {
	m := declaredCapacityRe.FindStringSubmatch(desc)
	if m == nil {
		return 0
	}
	total, err := strconv.Atoi(m[1])
	if err != nil || total <= 0 {
		return 0
	}
	// Дети — отдельное слагаемое источника, но для гостя это те же места:
	// «6 взрослых + 2 детей» значит, что поедут восемь человек.
	if m[2] != "" {
		if kids, err := strconv.Atoi(m[2]); err == nil && kids > 0 {
			total += kids
		}
	}
	// Потолок нужен потому, что «вместимость до 80 гостей» встречается у
	// банкетных залов на той же странице: это вместимость мероприятия, а
	// гости после него уезжают.
	if total > capacityMax {
		return 0
	}
	return total
}

// parseRoomSpecs — площадь и вместимость домика по строкам характеристик.
func parseRoomSpecs(specs []string) roomSpecs {
	var out roomSpecs
	for _, s := range specs {
		if m := areaSpecRe.FindStringSubmatch(s); m != nil {
			// Дробную часть отбрасываем: в карточке площадь показывается целыми
			// метрами, и «32.5» от «32» гостя ни к чему не обязывает.
			if n, err := strconv.Atoi(m[1]); err == nil && n > 0 {
				// Складываем: у домика площадь одна строкой, но если источник
				// перечислил комнаты по отдельности, гостю важна общая.
				out.AreaM2 += n
			}
			continue
		}
		// Все места строки, а не первое: источник иногда кладёт «2 двуспальные,
		// 1 односпальная» одним пунктом, и с FindStringSubmatch хвост терялся —
		// вместимость выходила заниженной, а гость не видел подходящий объект.
		for _, m := range bedSpecRe.FindAllStringSubmatch(s, -1) {
			n, err := strconv.Atoi(m[1])
			if err != nil || n <= 0 {
				continue
			}
			switch strings.ToLower(m[2]) {
			case "двуспальн":
				out.Guests += n * guestsPerDouble
			case "односпальн":
				out.Guests += n * guestsPerSingle
			case "диван":
				out.Guests += n * guestsPerSofa
			}
		}
	}
	return out
}

// detailRoomSpecs — характеристики самого вместительного домика объекта:
// вместимость и площадь ОДНОГО и того же домика.
//
// У объекта бывает несколько домиков разного размера. Гостю важно «сколько нас
// поместится» — то есть максимум, а не сумма: суммой мы обещали бы компанию из
// 12 человек там, где есть три домика по четверо, и каждый бронируется
// отдельно.
//
// Брать максимумы по отдельности нельзя, хотя так короче: вместимость пришла бы
// от одного домика, площадь от другого, и карточка описывала бы жильё, которого
// нет. Поэтому выбираем домик целиком — по вместимости, а при равной
// вместимости по площади.
func detailRoomSpecs(rooms map[string]pv12RoomWithSpecs) roomSpecs {
	var best roomSpecs
	for _, room := range rooms {
		s := parseRoom(room)
		if s.Guests > best.Guests || (s.Guests == best.Guests && s.AreaM2 > best.AreaM2) {
			best = s
		}
	}
	return best
}
